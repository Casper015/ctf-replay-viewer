"""Build the lobby catalog (and legacy redirect pages) from match metadata + replays.

Inputs
  content/matches/<key>.json      hand-edited bilingual metadata, one file per match
  site/data/matches/<key>.json    one replay per match

Outputs (generated, never edit by hand)
  site/data/catalog.json          lightweight index the lobby and viewer load first
  site/<legacy>.html              redirect stubs so links shared before v2 keep working

Usage
  python3 tools/build_catalog.py            # rebuild outputs
  python3 tools/build_catalog.py --report   # also print per-match facts to check copy against
  python3 tools/build_catalog.py --check    # validate only, write nothing (used by CI)
"""

from __future__ import annotations

import argparse
import json
import sys

from ctf_data import (CATALOG, CONTENT_DIR, MATCH_DIR, ROOT, SITE, capture_log, load_content,
                      match_facts, read_json, validate_meta, validate_replay, write_compact)

# URLs that existed before the v2 restructure -> match key (None = lobby).
LEGACY_PAGES = {
    "lobby.html": None,
    "replay_15p_sz15_m055282.html": "g15_rec",
    "replay_fable_vs_sol_vs_p1.html": "g3",
    "replay_opus_vs_player5.html": "g2",
    **{f"match_{key}.html": key for key in (
        "g15_rec", "g15_p5", "g8_record", "g8_astra_opus", "g8_p5_sol",
        "g4_record", "g4_duel", "g4_tie", "g4_three_way", "g3", "g2")},
}

REDIRECT_TEMPLATE = """<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="robots" content="noindex">
  <title>CTF Arena Replays</title>
  <meta http-equiv="refresh" content="0; url={target}">
  <link rel="canonical" href="{target}">
  <script>location.replace({target_js} + location.hash);</script>
</head>
<body>
  <!-- Generated by tools/build_catalog.py. Kept so links shared before v2 still work. -->
  <p><a href="{target}">{target}</a></p>
</body>
</html>
"""


def catalog_entry(meta: dict, replay: dict, size_bytes: int) -> dict:
    f = match_facts(replay)
    header = replay["header"]
    return {
        "key": meta["key"],
        "id": meta["id"],
        "featured": bool(meta.get("featured")),
        "tag": meta["tag"],
        "title": meta["title"],
        "desc": meta["desc"],
        "teams": f["teams"],
        "size": f["size"],
        "units": f["units"],
        "turns": f["turns"],
        "totalCaptures": f["total"],
        "leadChanges": f["lead_changes"],
        "standings": [{"team": r["team"], "name": r["name"], "score": r["score"]} for r in f["standings"]],
        "captures": capture_log(replay),
        "map": header["map"],
        "bases": header["bases"],
        "flagSpots": header["flag_spots"],
        "file": f"data/matches/{meta['key']}.json",
        "bytes": size_bytes,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--report", action="store_true", help="print facts to check match copy against")
    parser.add_argument("--check", action="store_true", help="validate only; don't write anything")
    args = parser.parse_args()

    metas = load_content()
    problems: list[str] = []
    seen: dict[str, str] = {}
    for meta in metas:
        rel = meta["_path"].relative_to(ROOT)
        problems += validate_meta(meta, str(rel))
        key = meta.get("key")
        if key in seen:
            problems.append(f"{rel}: duplicate key '{key}' (also in {seen[key]})")
        seen[key] = str(rel)
        if meta["_path"].stem != key:
            problems.append(f"{rel}: file name should be {key}.json to match its key")
    featured = [m["key"] for m in metas if m.get("featured")]
    if len(featured) > 1:
        problems.append(f"only one match can be featured, found: {', '.join(featured)}")

    entries = []
    for meta in metas:
        path = MATCH_DIR / f"{meta['key']}.json"
        if not path.exists():
            problems.append(f"{meta['key']}: replay {path.relative_to(ROOT)} not found")
            continue
        replay = read_json(path)
        replay_errs = validate_replay(replay)
        if replay_errs:
            problems += [f"{meta['key']}: {e}" for e in replay_errs]
            continue
        entry = catalog_entry(meta, replay, path.stat().st_size)
        entries.append(entry)
        if args.report:
            top = ", ".join(f"{s['name']} {s['score']}" for s in entry["standings"][:4])
            print(f"{entry['key']:<14} {entry['teams']:>2} teams {entry['totalCaptures']:>4} caps "
                  f"{entry['leadChanges']:>2} lead changes  {top}")

    orphans = sorted(p.stem for p in MATCH_DIR.glob("*.json") if p.stem not in seen)
    if orphans:
        print(f"note: replays without metadata (not listed): {', '.join(orphans)} "
              f"-> run tools/add_match.py or add {CONTENT_DIR.relative_to(ROOT)}/<key>.json")

    if problems:
        print("\n".join(f"error: {p}" for p in problems), file=sys.stderr)
        sys.exit(1)
    if args.check:
        print(f"ok: {len(entries)} matches valid")
        return

    write_compact(CATALOG, {"version": 2, "matches": entries})
    print(f"wrote {CATALOG.relative_to(ROOT)} ({len(entries)} matches, {CATALOG.stat().st_size // 1024} KB)")

    for name, key in LEGACY_PAGES.items():
        target = f"match.html?m={key}" if key else "index.html"
        (SITE / name).write_text(REDIRECT_TEMPLATE.format(target=target, target_js=json.dumps(target)),
                                 encoding="utf-8")


if __name__ == "__main__":
    main()
